# Python 2: Two sets of roll numbers - union, intersection, difference
set1 = {101, 102, 103, 104, 105}
set2 = {104, 105, 106, 107}
print("Set 1:", set1)
print("Set 2:", set2)
print("Union:", set1 | set2)
print("Intersection:", set1 & set2)
print("Difference (Set1 - Set2):", set1 - set2)
print("Difference (Set2 - Set1):", set2 - set1)
