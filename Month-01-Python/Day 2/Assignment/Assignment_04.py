# Type Conversion

a = input("Enter first number: ")
b = input("Enter second number: ")

a = int(a)
b = int(b)

add = a + b
sub = a - b
mul = a * b

print(type(a))
print(type(b))
print("Summation of two numbers: ",add)
print("Substraction of two numbers: ",sub)
print("Multiplication of two numbers: ",mul)